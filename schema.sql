PRAGMA foreign_keys=ON;
CREATE TABLE IF NOT EXISTS benches(id TEXT PRIMARY KEY, key_hash TEXT NOT NULL, name TEXT NOT NULL, demo INTEGER NOT NULL DEFAULT 0, created INTEGER NOT NULL, expires INTEGER NOT NULL);
CREATE TABLE IF NOT EXISTS repairs(id TEXT PRIMARY KEY, bench_id TEXT NOT NULL REFERENCES benches(id) ON DELETE CASCADE, revision INTEGER NOT NULL DEFAULT 0, data TEXT NOT NULL);
CREATE INDEX IF NOT EXISTS repairs_bench ON repairs(bench_id);
CREATE INDEX IF NOT EXISTS benches_expiry ON benches(expires);
CREATE TABLE IF NOT EXISTS limits(key TEXT PRIMARY KEY, count INTEGER NOT NULL, expires INTEGER NOT NULL);
